export interface Overrides { [openuiId: string]: Record<string, string> }

/** Allowed CSS properties for persisted visual tweaks (keeps overrides safe and maintainable). */
export const TWEAKABLE_PROPS = [
  "font-size", "font-weight", "line-height", "letter-spacing", "color", "background-color", "text-align",
  "padding", "padding-top", "padding-bottom", "padding-left", "padding-right",
  "margin", "margin-top", "margin-bottom", "gap", "width", "max-width", "min-height", "height",
  "border-radius", "border-width", "border-color", "box-shadow", "opacity",
  "display", "flex-direction", "justify-content", "align-items", "grid-template-columns",
] as const;

const VALUE_RE = /^[a-zA-Z0-9#%.,()\s/\-+*'"]+$/;

export function sanitizeTweak(prop: string, value: string): string | null {
  if (!(TWEAKABLE_PROPS as readonly string[]).includes(prop)) return null;
  if (value.length > 160 || !VALUE_RE.test(value)) return null;
  if (/url\s*\(|expression|javascript:|@import/i.test(value)) return null;
  return value.trim();
}

export function renderOverridesCss(o: Overrides): string {
  const rules = Object.entries(o).map(([id, props]) => {
    const body = Object.entries(props)
      .map(([k, v]) => [k, sanitizeTweak(k, v)] as const)
      .filter(([, v]) => v !== null)
      .map(([k, v]) => `  ${k}: ${v} !important;`).join("\n");
    return body ? `[data-openui-id="${id.replace(/"/g, "")}"] {\n${body}\n}` : "";
  }).filter(Boolean);
  return `/* Generated by OpenUI Engine from openui.overrides.json — edit via the visual editor or apply_visual_tweaks. */\n${rules.join("\n\n")}\n`;
}

