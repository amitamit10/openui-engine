export interface BuiltSite { files: Record<string, string> }

/** Render a full static site (HTML + tokens.css + styles.css + overrides.css + app.js). */
export function buildSite(spec: PageSpec, tokens: DesignTokens, overrides: Overrides = {}): BuiltSite {
  const ctx = { tokens, spec };
  const body = spec.sections.map((s) => {
    const r = RENDERERS[s.type];
    if (!r) throw new Error(`Unknown section type "${s.type}" (section ${s.id})`);
    return r(s, ctx);
  }).join("\n");
  const fonts = tokens.font.googleFamilies.length
    ? `<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link rel="stylesheet" href="https://fonts.googleapis.com/css2?${tokens.font.googleFamilies.map((f) => "family=" + f).join("&")}&display=swap">`
    : "";
  const html = `<!doctype html>
<html lang="${esc(spec.lang ?? "en")}" data-motion="${tokens.motion.intensity}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(spec.title)}</title>
<meta name="description" content="${esc(spec.description)}">
<meta name="theme-color" content="${tokens.color.bg}">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Crect width='32' height='32' rx='8' fill='${encodeURIComponent(tokens.color.accent)}'/%3E%3C/svg%3E">
${fonts}
<link rel="stylesheet" href="tokens.css">
<link rel="stylesheet" href="styles.css">
<link rel="stylesheet" href="overrides.css">
</head>
<body data-style="${tokens.meta.style}" data-mode-ui="${tokens.meta.mode}">
<a class="skip" href="#main">Skip to content</a>
<main id="main" style="display:contents">
${body}
</main>
<script src="app.js" defer></script>
</body>
</html>
`;
  // navbar + footer should not sit inside <main>; split them out for correct landmarks.
  const files: Record<string, string> = {
    "index.html": landmarks(html),
    "tokens.css": renderTokensCss(tokens),
    "styles.css": BASE_CSS,
    "overrides.css": renderOverridesCss(overrides),
    "app.js": APP_JS,
  };
  return { files };
}

/** Move <header class="nav"> before and <footer> after <main> so landmarks are valid. */
function landmarks(html: string): string {
  const header = html.match(/<header class="nav"[\s\S]*?<\/header>/)?.[0];
  const footer = html.match(/<footer class="footer"[\s\S]*?<\/footer>/)?.[0];
  let out = html;
  if (header) out = out.replace(header, "");
  if (footer) out = out.replace(footer, "");
  out = out.replace('<main id="main" style="display:contents">', `${header ?? ""}\n<main id="main">`);
  out = out.replace("</main>", `</main>\n${footer ?? ""}`);
  return out;
}
